-- ==============================================================================
-- Configuring Forced RLS Policies
-- ==============================================================================

DO $$
DECLARE
    tbl text;
    rls_tables text[] := ARRAY[
        'bench_rls',
        'bench_rls_orders',
        'bench_rls_order_items',
        'bench_rls_order_payments',
        'bench_skew_rls'
    ];
BEGIN
    FOREACH tbl IN ARRAY rls_tables LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tbl);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', tbl);
        EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', tbl);
        EXECUTE format('
            CREATE POLICY tenant_isolation ON %I
            FOR ALL TO nexusops_app
            USING (tenant_id = nullif(current_setting(''app.tenant_id'', true), '''')::uuid)
            WITH CHECK (tenant_id = nullif(current_setting(''app.tenant_id'', true), '''')::uuid)
        ', tbl);
    END LOOP;
END $$;

-- Grant permissions to application role
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO nexusops_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO nexusops_app;

