\timing on

-- 1. Microbenchmark Tables (Point Lookup, Paged List, Tenant Count, Point Insert)
DROP TABLE IF EXISTS bench_filter CASCADE;
DROP TABLE IF EXISTS bench_rls CASCADE;

CREATE TABLE bench_filter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_bench_filter_tenant_id ON bench_filter(tenant_id, id);

CREATE TABLE bench_rls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_bench_rls_tenant_id ON bench_rls(tenant_id, id);

-- 2. Join Benchmark Tables (Two-Table & Three-Table Relational Graph)
DROP TABLE IF EXISTS bench_order_payments CASCADE;
DROP TABLE IF EXISTS bench_order_items CASCADE;
DROP TABLE IF EXISTS bench_orders CASCADE;
DROP TABLE IF EXISTS bench_rls_order_payments CASCADE;
DROP TABLE IF EXISTS bench_rls_order_items CASCADE;
DROP TABLE IF EXISTS bench_rls_orders CASCADE;

CREATE TABLE bench_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    order_num VARCHAR(64) NOT NULL,
    total_cents INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_bench_orders_tenant_id ON bench_orders(tenant_id, id);

CREATE TABLE bench_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    order_id BIGINT NOT NULL,
    item_name VARCHAR(128) NOT NULL,
    price_cents INT NOT NULL
);
CREATE INDEX idx_bench_order_items_tenant_order ON bench_order_items(tenant_id, order_id);

CREATE TABLE bench_order_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    order_id BIGINT NOT NULL,
    amount_cents INT NOT NULL,
    status VARCHAR(32) NOT NULL
);
CREATE INDEX idx_bench_order_payments_tenant_order ON bench_order_payments(tenant_id, order_id);

CREATE TABLE bench_rls_orders (LIKE bench_orders INCLUDING ALL);
CREATE TABLE bench_rls_order_items (LIKE bench_order_items INCLUDING ALL);
CREATE TABLE bench_rls_order_payments (LIKE bench_order_payments INCLUDING ALL);

-- 3. Tenant Size Skew Benchmark Tables (Pareto 80/20 Distribution)
DROP TABLE IF EXISTS bench_skew_filter CASCADE;
DROP TABLE IF EXISTS bench_skew_rls CASCADE;

CREATE TABLE bench_skew_filter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_bench_skew_filter_tenant_id ON bench_skew_filter(tenant_id, id);

CREATE TABLE bench_skew_rls (LIKE bench_skew_filter INCLUDING ALL);

